// Package render produces the zsh code that ali's files and shell block contain.
package render

import (
	"sort"
	"strings"

	"github.com/josh-quinn/ali/internal/alias"
)

// Markers delimit the block that `ali init` manages inside .zshrc.
const (
	BlockStart = "# >>> ali >>>"
	BlockEnd   = "# <<< ali <<<"
)

// Quote wraps s in single quotes so zsh treats it literally.
func Quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// Zsh renders aliases.zsh. It first removes every alias a previous load
// defined (tracked in _ali_names) so removed or renamed aliases vanish from a
// live shell without touching the user's own aliases.
func Zsh(aliases []alias.Alias) string {
	sorted := append([]alias.Alias(nil), aliases...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })

	var b strings.Builder
	b.WriteString("# generated by ali; do not edit (edit aliases.toml or use the ali command)\n")
	b.WriteString("for _n in $_ali_names; do unalias -- \"$_n\" 2>/dev/null; done\n")
	names := make([]string, len(sorted))
	for i, a := range sorted {
		names[i] = a.Name
	}
	b.WriteString("_ali_names=(" + strings.Join(names, " ") + ")\n")
	for _, a := range sorted {
		b.WriteString("alias -- " + a.Name + "=" + Quote(a.Command) + "\n")
	}
	return b.String()
}

// Block returns the managed .zshrc block. It only sources a file and defines a
// wrapper; it never runs the ali binary at shell startup.
func Block() string {
	return BlockStart + `
_ali_dir="${ALI_CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/ali}"
[ -f "$_ali_dir/aliases.zsh" ] && source "$_ali_dir/aliases.zsh"
ali() { command ali "$@"; local rc=$?; [ -f "$_ali_dir/aliases.zsh" ] && source "$_ali_dir/aliases.zsh"; return $rc; }
` + BlockEnd + "\n"
}
