// Package render produces the zsh code that ali's files and shell block contain.
package render

import (
	"crypto/sha256"
	"encoding/hex"
	"sort"
	"strconv"
	"strings"

	"github.com/josh-quinn/ali/internal/alias"
)

// Markers delimit the block that `ali init` manages inside .zshrc.
const (
	BlockStart = "# >>> ali >>>"
	BlockEnd   = "# <<< ali <<<"
	// BlockVersion is bumped whenever the block text changes, so people reading
	// their .zshrc can tell which revision they have. Upgrades compare the whole
	// text, not this number (ADR 0029).
	BlockVersion = 2
)

// Quote wraps s in single quotes so zsh treats it literally.
func Quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// Gen identifies a set of alias definitions. aliases.zsh records it so that
// "ali doctor" can tell whether the shell's startup snapshot still matches the
// store before comparing them.
func Gen(aliases []alias.Alias) string {
	sorted := append([]alias.Alias(nil), aliases...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })
	h := sha256.New()
	for _, a := range sorted {
		h.Write([]byte(a.Name + "\x00" + a.Command + "\x00"))
	}
	return hex.EncodeToString(h.Sum(nil))[:16]
}

// Zsh renders aliases.zsh. Startup cost matters (Constitution I), so it uses
// zsh's array set operations instead of looping over every alias:
//
//   - names ali no longer defines (old minus new) get their pre-ali original
//     back from _ali_prev, or are unaliased (ADR 0028);
//   - names new to ali that already exist as someone else's alias (e.g. Oh My
//     Zsh's gp) have that original remembered for this session only.
//
// Builtins are backslash-escaped so a user alias cannot intercept them, and
// names are quoted as defence in depth (ADR 0021).
func Zsh(aliases []alias.Alias) string {
	sorted := append([]alias.Alias(nil), aliases...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })
	names := make([]string, len(sorted))
	for i, a := range sorted {
		names[i] = Quote(a.Name)
	}

	var b strings.Builder
	b.WriteString("# generated by ali; do not edit (edit aliases.toml or use the ali command)\n")
	// $aliases and $functions come from zsh/parameter; assigning to them before
	// the module is loaded would silently create ordinary arrays.
	b.WriteString("\\zmodload -i zsh/parameter 2>/dev/null\n")
	b.WriteString("\\typeset -gA _ali_prev\n")
	b.WriteString("\\typeset -ga _ali_names\n")
	b.WriteString("_ali_old=($_ali_names)\n")
	b.WriteString("_ali_names=(" + strings.Join(names, " ") + ")\n")
	b.WriteString("for _n in ${_ali_old:|_ali_names}; do\n")
	b.WriteString("  if (( ${+_ali_prev[$_n]} )); then aliases[$_n]=${_ali_prev[$_n]}; else \\unalias -- \"$_n\" 2>/dev/null; fi\n")
	b.WriteString("done\n")
	b.WriteString("_ali_k=(${(k)aliases})\n")
	b.WriteString("_ali_k=(${_ali_k:*_ali_names})\n")
	b.WriteString("for _n in ${_ali_k:|_ali_old}; do\n")
	b.WriteString("  (( ${+_ali_prev[$_n]} )) || _ali_prev[$_n]=${aliases[$_n]}\n")
	b.WriteString("done\n")
	b.WriteString("\\unset _n _ali_k _ali_old\n")
	b.WriteString("_ali_gen=" + Quote(Gen(sorted)) + "\n")
	for _, a := range sorted {
		b.WriteString("\\alias -- " + a.Name + "=" + Quote(a.Command) + "\n")
	}
	return b.String()
}

// Block returns the managed .zshrc block. It only sources a file and defines a
// wrapper; it never runs the ali binary at shell startup. Builtins are
// backslash-escaped because functions are parsed when defined, so a user alias
// of "command" or "source" would otherwise hijack the wrapper.
func Block() string {
	return BlockStart + "\n# ali block v" + strconv.Itoa(BlockVersion) + ", managed by ali init zsh" + `
_ali_dir="${ALI_CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/ali}"
[ -f "$_ali_dir/aliases.zsh" ] && \source "$_ali_dir/aliases.zsh"
# At the first prompt, after every rc file has run, keep a copy of the alias
# table so "ali doctor" can spot ali aliases that something loaded later changed.
# One bulk copy, no loop, no process; the hook then removes itself.
_ali_startup_check() {
  \typeset -gA _ali_at_start
  _ali_at_start=("${(@kv)aliases}")
  _ali_gen_at_start=$_ali_gen
  \add-zsh-hook -d precmd _ali_startup_check
}
\autoload -Uz add-zsh-hook
\add-zsh-hook precmd _ali_startup_check
ali() {
  # For "ali add NAME", tell the binary what NAME means in this shell (ADR 0027).
  if [[ $1 == doctor ]]; then
    # Pass the startup snapshot: generation, then NUL-separated name/value pairs.
    \print -rN -- "${_ali_gen_at_start-}" "${(@kv)_ali_at_start}" | \command ali doctor --shell-state - "${@:2}"
  elif [[ $1 == add && -n $2 ]]; then
    \local _d=
    if (( ${+aliases[$2]} && ! ${_ali_names[(Ie)$2]} )); then _d="alias"$'\t'"${aliases[$2]}"
    elif (( ${+functions[$2]} )); then _d=function
    fi
    ALI_SHELL_DEF="$_d" \command ali "$@"
  else
    \command ali "$@"
  fi
  \local rc=$?
  [ -f "$_ali_dir/aliases.zsh" ] && \source "$_ali_dir/aliases.zsh"
  \unset _n
  \return $rc
}
` + BlockEnd + "\n"
}
