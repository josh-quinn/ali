// Round-trip: every special-character command must run exactly as typed.
func TestZshRoundTrip(t *testing.T) {
	zsh, err := exec.LookPath("zsh")
	if err != nil {
		t.Skip("zsh not installed")
	}
	cmds := []string{
		`echo 'it'\''s'`,
		`echo "$HOME" '$HOME'`,
		"echo `echo bt`",
		`echo a && echo b | cat`,
		"echo héllo ✓",
		"echo one\necho two",
		`printf '%s\n' "a b"`,
	}
	for _, c := range cmds {
		dir := t.TempDir()
		f := dir + "/aliases.zsh"
		os.WriteFile(f, []byte(Zsh([]alias.Alias{{Name: "t1", Command: c, Group: "x"}})), 0o600)
		script := "setopt aliases; source " + f + "\neval t1"
		got, err := exec.Command(zsh, "-f", "-c", script).CombinedOutput()
		if err != nil {
			t.Fatalf("%q: %v: %s", c, err, got)
		}
		want, _ := exec.Command(zsh, "-f", "-c", c).CombinedOutput()
		if string(got) != string(want) {
			t.Errorf("%q: alias output %q, direct output %q", c, got, want)
		}
	}
}

func TestZshUnaliasesPrevious(t *testing.T) {
	zsh, err := exec.LookPath("zsh")
	if err != nil {
		t.Skip("zsh not installed")
	}
	dir := t.TempDir()
	f := dir + "/aliases.zsh"
	os.WriteFile(f, []byte(Zsh([]alias.Alias{{Name: "old", Command: "echo old", Group: "x"}})), 0o600)
	script := "source " + f + "\n"
	g := dir + "/b.zsh"
	os.WriteFile(g, []byte(Zsh(nil)), 0o600)
	script += "source " + g + "\nalias old || echo gone"
	out, _ := exec.Command(zsh, "-f", "-c", script).CombinedOutput()
	if !strings.Contains(string(out), "gone") {
		t.Errorf("removed alias still defined: %s", out)
	}
}

func TestBlock(t *testing.T) {
	b := Block()
	if !strings.Contains(b, "# ali block v2, managed by ali init zsh") {
		t.Errorf("block has no version line:\n%s", b)
	}
	if !strings.HasPrefix(b, BlockStart) || !strings.HasSuffix(strings.TrimSpace(b), BlockEnd) {
		t.Errorf("block markers missing:\n%s", b)
	}
	if strings.Contains(b, `eval "$(ali`) {
		t.Error("block must not spawn ali at shell startup")
	}
}

